import logging


class _FloodLogHandler(logging.Handler):
    """Telethon sleeps through FloodWaits <= 60 s by itself and only logs it.
    Forward those lines to our log/console so waits are never invisible."""

    def __init__(self, db):
        super().__init__(logging.INFO)
        self.db = db

    def emit(self, record):
        try:
            text = record.getMessage()
            if 'flood wait' in text.lower():
                self.db.log('WARN', f'⏳ {text}')
        except Exception:
            pass


def _attach_flood_logger(db):
    lg = logging.getLogger('telethon')
    if lg.level == logging.NOTSET or lg.level > logging.INFO:
        lg.setLevel(logging.INFO)
    if not any(isinstance(h, _FloodLogHandler) for h in lg.handlers):
        lg.addHandler(_FloodLogHandler(db))


class Worker:
    def __init__(self):
        self.s = load_settings()
        self.db = Database()
        self.loop = None
        self.client = None
        self.thread = None
        self.running = False
        self.scanning = False
        self.scan_future = None
        self.stop_event = threading.Event()
        self.stats = {'status': 'stopped', 'source': '', 'checked': 0, 'found': 0, 'skipped': 0, 'published': 0, 'files_sent': 0, 'polls_seen': 0, 'anonymous_quizzes': 0, 'answer_failures': 0, 'duplicates': 0, 'flood_waits': 0, 'flood_wait_seconds': 0, 'vote_flood_waits': 0, 'error': ''}
        self.hist = {}
        self.backup = TelegramBackup(self.db, self.s.storage_channel)
        self.intake = IntakeManager(self.db, on_change=self.backup.request)
        self._backup_task = None
        self.quizbot_word = QuizBotWord(self.db)
        self.lock = threading.RLock()

    def start(self):
        with self.lock:
            if self.thread and self.thread.is_alive():
                return
            self.thread = threading.Thread(target=self.run, name='telegram-userbot', daemon=True)
            self.thread.start()

    def run(self):
        self.loop = asyncio.new_event_loop()
        asyncio.set_event_loop(self.loop)
        try:
            self.loop.run_until_complete(self.main())
        except Exception as exc:
            self.running = False
            self.db.hb('error', str(exc))
            self.db.log('ERROR', f'Worker: {exc}')
        finally:
            self.running = False

    async def main(self):
        if not self.s.session_string:
            self.db.hb('error', 'TELEGRAM_SESSION_STRING yo‘q')
            return
        self.client = TelegramClient(StringSession(self.s.session_string), self.s.api_id, self.s.api_hash)
        await self.client.connect()
        if not await self.client.is_user_authorized():
            self.db.hb('error', 'Session authorized emas')
            return

        # Restore state from the Telegram storage channel BEFORE doing any work
        # (only when the local DB is empty, e.g. after a redeploy/restart).
        try:
            if await self.backup.restore_if_needed(self.client):
                self.db.log('INFO', 'Holat Telegram storage kanalidan tiklandi')
        except Exception as exc:
            self.backup.last_error = f'restore: {type(exc).__name__}: {exc}'
            self.db.log('ERROR', f'Storage restore: {type(exc).__name__}: {exc}')
        if self.backup.enabled:
            self._backup_task = asyncio.create_task(self.backup.run(self.client))
        else:
            self.db.log('WARN', 'STORAGE_CHANNEL berilmagan: holat qayta ishga tushganda yo‘qoladi')

        _attach_flood_logger(self.db)
        op = Operator()
        self.running = True
        self.db.hb('running', 'Telegram ulangan')
        self.db.log('INFO', 'UserBot connected')

        @self.client.on(events.NewMessage(incoming=True))
        async def incoming(e):
            if not e.is_private:
                return
            try:
                # Messages generated by QuizBot belong to the active QuizBot session,
                # not to the regular operator, manual intake or the link handler.
                try:
                    sender = await e.get_sender()
                    if str(getattr(sender, "username", "") or "").lower() == "quizbot":
                        return
                except Exception:
                    pass
                # QuizBot links are handled in an isolated per-link workflow.
                if await self.quizbot_word.handle_link(self.client, e):
                    return
                # Intake has priority: INFO/YAKUNLASH, photos and Telegram quizzes
                # are consumed here. Anything else falls through to the normal operator.
                consumed = await self.intake.handle(self.client, e)
                if consumed:
                    return

                text = (e.raw_text or '').strip()
                if not text:
                    return
                history = self.hist.setdefault(str(e.sender_id), [])
                answer = await asyncio.to_thread(op.reply, history, text)  # keep the event loop free
                history.extend([{'role': 'user', 'content': text}, {'role': 'assistant', 'content': answer}])
                del history[:-14]
                await e.reply(answer)
            except Exception as exc:
                self.db.log('ERROR', f'Incoming handler: {exc}')

        await self.client.run_until_disconnected()

    def start_scan(self, rows=None):
        with self.lock:
            if not self.running or self.loop is None or self.client is None:
                self.stats.update(status='error', error='UserBot hali Telegramga ulanmagan')
                return False
            if self.scanning:
                return False
            rows = rows if rows is not None else self.db.sources()
            rows = [r for r in rows if int(r.get('enabled', 1))]
            if not rows:
                self.stats.update(status='error', error='Scanner uchun manba saqlanmagan')
                return False
            self.stop_event.clear()
            self.scanning = True
            self.stats = {'status': 'starting', 'source': '', 'checked': 0, 'found': 0, 'skipped': 0, 'published': 0, 'files_sent': 0, 'polls_seen': 0, 'anonymous_quizzes': 0, 'answer_failures': 0, 'duplicates': 0, 'flood_waits': 0, 'flood_wait_seconds': 0, 'vote_flood_waits': 0, 'error': ''}
            self.db.log('INFO', f'Scanner START: {len(rows)} source')
            self.scan_future = asyncio.run_coroutine_threadsafe(self._scan_all(rows), self.loop)
            return True

    async def _scan_all(self, rows):
        try:
            for row in rows:
                if self.stop_event.is_set():
                    break
                source = str(row['source']).strip()
                try:
                    self.db.log('INFO', f"Scan START: {source}; mode={row.get('scan_mode','target')}; target={row['target_count']}")
                    n = await scan(
                        self.client, self.db, source, int(row['target_count']),
                        self.stop_event, self.s, self.stats,
                        output_chat=str(row.get('output_chat') or '').strip(),
                        publish_enabled=bool(row.get('publish_enabled', 0)),
                        file_publish_enabled=bool(row.get('file_publish_enabled', 1)),
                        per_file=int(row.get('per_file', 20) or 20),
                        scan_mode=str(row.get('scan_mode') or 'target'),
                    )
                    self.db.log('INFO', f'Scan DONE: {source}; found={n}')
                except Exception as exc:
                    self.db.log('ERROR', f'Scan {source}: {exc}')
                    self.stats['error'] = str(exc)
                    self.stats['status'] = 'error'
                    # Continue to the next configured source unless user pressed stop.
            if self.stop_event.is_set():
                self.stats['status'] = 'stopped'
            elif self.stats.get('status') != 'error':
                self.stats['status'] = 'completed'
        finally:
            self.scanning = False
            self.scan_future = None
            self.backup.request()

    def stop_scan(self):
        with self.lock:
            if not self.scanning:
                return False
            self.stop_event.set()
            self.stats['status'] = 'stopping'
            self.db.log('INFO', 'Scanner STOP requested')
            return True


W = None


def get_worker():
    global W
    if W is None:
        W = Worker()
    return W


def ensure_worker_started():
    get_worker().start()
    return True


def worker_is_alive():
    w = get_worker()
    return bool(w.thread and w.thread.is_alive() and w.running)
